#!/usr/bin/env python3
"""Write the verified prop facing table from the facing audit workflow result.

    python3 tools/props/facing_table.py WORKFLOW_OUTPUT.json

Input: the result of the workflow decimation-prop-facing-audit ({merged, judged}): per prop the
front direction at metadata 2..5, mount, long axis, evidence, from two independent readers that
agreed (merged) or a judge that settled a disagreement (judged). Output:
  docs/references/prop_facing.tsv          (reference, every column, committed)
  dev/src/main/resources/assets/deciworldgen/prop_facing.tsv  (read by city/PropFacing)
Columns: prop mount front_m2 front_m3 front_m4 front_m5 axis_m2 axis_m3 axis_m4 axis_m5 symmetric
confidence source looks_like front_feature wall_side meta_note evidence.
Front letters E S W N, "-" symmetric or unknown; axis x z or "-". Rows in
docs/references/prop_facing_overrides.tsv (corrections checked in game with the dev test
`facing`) replace the audit's front.
"""
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


def letter(v):
    v = str(v or "").strip().upper()
    for c in v:
        if c in "NESW":
            return c
    return "-"


def axis(v):
    v = str(v or "").strip().lower()
    return v[0] if v[:1] in ("x", "z") else "-"


def clean(s):
    return str(s or "").replace("\t", " ").replace("\n", " ").replace("—", ", ").replace("–", "-")


def main():
    data = json.load(open(sys.argv[1]))
    data = data.get("result", data)
    rows = {}
    for src, items in (("agreed", data.get("merged", [])), ("judged", data.get("judged", []))):
        for p in items:
            rows[p["name"]] = (p, src)
    over = os.path.join(ROOT, "docs/references/prop_facing_overrides.tsv")
    fixes = {}
    if os.path.isfile(over):
        for line in open(over):
            if line.startswith("#") or not line.strip():
                continue
            c = line.rstrip("\n").split("\t")
            fixes[c[0]] = c[1:5]
    head = ["prop", "mount", "front_m2", "front_m3", "front_m4", "front_m5", "axis_m2", "axis_m3", "axis_m4", "axis_m5",
            "symmetric", "confidence", "source", "looks_like", "front_feature", "wall_side", "meta_note", "evidence"]
    out = ["\t".join(head)]
    game = ["\t".join(head[:10])]
    for name in sorted(rows):
        p, src = rows[name]
        f = p.get("front_at_meta", {})
        a = p.get("long_axis_at_meta", {})
        fr = [letter(f.get(k)) for k in ("m2", "m3", "m4", "m5")]
        if p.get("symmetric"):
            fr = ["-"] * 4
        if name in fixes:
            fr = fixes[name]
            src = "in game"
        ax = [axis(a.get(k)) for k in ("m2", "m3", "m4", "m5")]
        row = [name, p.get("mount", "")] + fr + ax + [str(bool(p.get("symmetric"))).lower(), p.get("confidence", ""), src,
               clean(p.get("looks_like")), clean(p.get("front_feature")), clean(p.get("wall_side_at_meta")),
               clean(p.get("meta_range_note")), clean(p.get("evidence"))[:400]]
        out.append("\t".join(row))
        if p.get("confidence") != "low":
            game.append("\t".join(row[:10]))
    open(os.path.join(ROOT, "docs/references/prop_facing.tsv"), "w").write("\n".join(out) + "\n")
    res = os.path.join(ROOT, "dev/src/main/resources/assets/deciworldgen/prop_facing.tsv")
    open(res, "w").write("# generated by tools/props/facing_table.py from docs/references/prop_facing.tsv (low confidence rows left out)\n"
                         + "\n".join(game) + "\n")
    print("props %d (agreed %d, judged %d), in the game table %d"
          % (len(rows), sum(1 for v in rows.values() if v[1] == "agreed"), sum(1 for v in rows.values() if v[1] == "judged"),
             len(game) - 1))


if __name__ == "__main__":
    main()
